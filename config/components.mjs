const titleCase = (slug) =>
  slug
    .split("-")
    .map((word) => {
      if (word === "kbd") return "Kbd"
      if (word === "otp") return "OTP"
      return word.charAt(0).toUpperCase() + word.slice(1)
    })
    .join(" ")

